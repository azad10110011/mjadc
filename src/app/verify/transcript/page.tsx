'use client'

// Public page opened by scanning the QR code on a transcript.
// /verify/transcript/?id=<student_id>&exam=<exam_id>&t=<token>

import { useSearchParams } from 'next/navigation'
import { Suspense, useEffect, useState } from 'react'
import { api } from '@/lib/api'
import { photoUrl } from '@/lib/photo'
import { BadgeCheck, ShieldAlert, AlertTriangle } from 'lucide-react'
import {
  COLLEGE_ADDRESS,
  COLLEGE_NAME,
  partText,
  totalText,
  useCollegeLogo,
  type TranscriptData,
} from '@/components/transcript/TranscriptGenerator'

type VerifyResult =
  | ({ verified: true; verified_since: string | null } & TranscriptData)
  | { verified: false; message: string }

const OFF_MSG = 'Please contact Exam office to online verify your Transcript.'

function VerifyContent() {
  const search = useSearchParams()
  const logoSrc = useCollegeLogo()
  const [data, setData] = useState<VerifyResult | null>(null)
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    const id = search.get('id')
    const exam = search.get('exam')
    const t = search.get('t')
    if (!id || !exam || !t) {
      const timer = setTimeout(() => { setError(`Invalid verification link. ${OFF_MSG}`); setLoading(false) }, 0)
      return () => clearTimeout(timer)
    }
    const q = new URLSearchParams({ id, exam, t })
    api
      .get<{ data: VerifyResult }>(`/public/transcript-verify?${q.toString()}`)
      .then((res) => setData(res.data))
      .catch((err: unknown) => setError(err instanceof Error ? err.message : `Verification failed. ${OFF_MSG}`))
      .finally(() => setLoading(false))
  }, [search])

  return (
    <div className="min-h-screen bg-gradient-to-b from-blue-50 to-slate-100 px-4 py-8">
      <div className="mx-auto max-w-xl">
        <div className="overflow-hidden rounded-2xl border-2 border-blue-900 bg-white shadow-lg">
          <div className="border-b-2 border-blue-900 bg-gradient-to-b from-blue-100 to-blue-50 px-4 py-5 text-center">
            <div className="flex items-center justify-center gap-3">
              {logoSrc && (
                // eslint-disable-next-line @next/next/no-img-element
                <img src={logoSrc} alt="Logo" className="h-14 w-14 object-contain" />
              )}
              <div>
                <h1 className="font-serif text-lg font-bold leading-tight text-blue-900 sm:text-xl">{COLLEGE_NAME}</h1>
                <p className="text-xs text-gray-600">{COLLEGE_ADDRESS}</p>
              </div>
            </div>
            <p className="mt-3 inline-block rounded-full bg-blue-900 px-4 py-0.5 text-xs font-bold tracking-[0.2em] text-white">
              TRANSCRIPT VERIFICATION
            </p>
          </div>

          <div className="p-5">
            {loading && <p className="py-8 text-center text-gray-500">Verifying...</p>}

            {!loading && error && (
              <div className="flex items-start gap-3 rounded-xl border border-red-200 bg-red-50 p-4 text-red-700">
                <AlertTriangle className="mt-0.5 h-6 w-6 shrink-0" />
                <p className="text-sm font-medium">{error}</p>
              </div>
            )}

            {data && !data.verified && (
              <div className="flex flex-col items-center gap-3 rounded-xl border border-amber-300 bg-amber-50 p-6 text-center">
                <ShieldAlert className="h-12 w-12 text-amber-600" />
                <p className="text-base font-semibold text-amber-900">{data.message || OFF_MSG}</p>
              </div>
            )}

            {data && data.verified && <Verified t={data} />}
          </div>
        </div>
        <p className="mt-4 text-center text-xs text-gray-500">
          This page is generated by the {COLLEGE_NAME} result system.
        </p>
      </div>
    </div>
  )
}

function Verified({ t }: { t: TranscriptData & { verified_since: string | null } }) {
  const rows: [string, string][] = [
    ["Father's Name", t.father_name || 'N/A'],
    ["Mother's Name", t.mother_name || 'N/A'],
    ['Class', t.class],
    ['Group', t.group || 'N/A'],
    ['Academic Session', t.academic_session || 'N/A'],
    ['Exam', `${t.exam_name} ${t.year}`],
  ]
  return (
    <div className="space-y-4">
      <div className="flex items-center gap-3 rounded-xl border border-green-300 bg-green-50 p-3">
        <BadgeCheck className="h-9 w-9 shrink-0 text-green-600" />
        <div>
          <p className="font-bold text-green-800">Verified Transcript</p>
          <p className="text-xs text-green-700">This transcript is authentic and issued by the college.</p>
        </div>
      </div>

      <div className="flex items-center gap-4">
        {t.photo_path ? (
          // eslint-disable-next-line @next/next/no-img-element
          <img src={photoUrl(t.photo_path)} alt={t.name}
            className="h-24 w-20 shrink-0 rounded-md border-2 border-blue-900 object-cover" />
        ) : null}
        <div className="min-w-0">
          <p className="text-lg font-bold text-gray-900">{t.name}</p>
          <p className="font-mono text-sm text-gray-600">Roll / ID: {t.student_id}</p>
        </div>
      </div>

      <dl className="grid grid-cols-1 gap-x-4 gap-y-1 text-sm sm:grid-cols-2">
        {rows.map(([k, v]) => (
          <div key={k} className="flex gap-1">
            <dt className="font-semibold text-blue-900">{k}:</dt>
            <dd className="text-gray-800">{v}</dd>
          </div>
        ))}
      </dl>

      <div className="grid grid-cols-3 gap-2 text-center">
        <div className="rounded-lg bg-blue-900 p-2 text-white">
          <p className="text-[10px] font-semibold uppercase tracking-wide">GPA</p>
          <p className="text-xl font-bold">{t.overall_gpa.toFixed(2)}</p>
        </div>
        <div className="rounded-lg bg-blue-900 p-2 text-white">
          <p className="text-[10px] font-semibold uppercase tracking-wide">Grade</p>
          <p className="text-xl font-bold">{t.overall_grade}</p>
        </div>
        <div className="rounded-lg border border-blue-200 bg-blue-50 p-2">
          <p className="text-[10px] font-semibold uppercase tracking-wide text-blue-900">Without Optional</p>
          <p className="text-xl font-bold text-gray-900">{t.gpa_without_optional.toFixed(2)}</p>
        </div>
      </div>

      <div className="overflow-x-auto rounded-lg border border-slate-300">
        <table className="w-full text-xs sm:text-sm">
          <thead className="bg-blue-900 text-white">
            <tr>
              <th className="px-1.5 py-1.5 text-left">Subject</th>
              <th className="px-1 py-1.5">CQ</th>
              <th className="px-1 py-1.5">MCQ</th>
              <th className="px-1 py-1.5">Prac.</th>
              <th className="px-1 py-1.5">Total</th>
              <th className="px-1 py-1.5">Grade</th>
              <th className="px-1 py-1.5">GP</th>
            </tr>
          </thead>
          <tbody>
            {t.subjects.map((s, i) => (
              <tr key={`${s.subject}-${i}`} className="border-t border-slate-200 even:bg-blue-50">
                <td className="px-1.5 py-1.5 font-medium">
                  {s.subject}
                  {s.code && <span className="ml-1 text-[10px] text-gray-500">({s.code})</span>}
                  {s.is_optional && <span className="block text-[10px] font-semibold text-blue-700">Optional</span>}
                </td>
                <td className="px-1 py-1.5 text-center">{partText(s.parts?.cq)}</td>
                <td className="px-1 py-1.5 text-center">{partText(s.parts?.mcq)}</td>
                <td className="px-1 py-1.5 text-center">{partText(s.parts?.practical)}</td>
                <td className="px-1 py-1.5 text-center font-semibold">{totalText(s)}</td>
                <td className="px-1 py-1.5 text-center font-semibold">{s.grade}</td>
                <td className="px-1 py-1.5 text-center">{s.gpa.toFixed(2)}</td>
              </tr>
            ))}
            {t.subjects.length === 0 && (
              <tr><td colSpan={7} className="px-2 py-4 text-center text-gray-500">No subject results recorded</td></tr>
            )}
          </tbody>
        </table>
      </div>
    </div>
  )
}

export default function TranscriptVerifyPublicPage() {
  return (
    <Suspense fallback={<div className="p-6 text-center">Loading...</div>}>
      <VerifyContent />
    </Suspense>
  )
}
